const LANGS = ['en', 'es', 'it'];
const L = () => (window.JUTZ && JUTZ.lang) || null;
function lang() { const l = L(); const v = l ? l.get() : 'en'; return LANGS.includes(v) ? v : 'en'; }
function fill(s, v) { return v ? String(s).replace(/\{(\w+)\}/g, (m, k) => (v[k] != null ? v[k] : m)) : s; }
function t(k, v) { const l = lang(); const s = (S[l] && S[l][k] != null) ? S[l][k] : (S.en[k] != null ? S.en[k] : k); return fill(s, v); }
/* canvas phrase lookup: English text -> key (exact), then {n} patterns */
let exact = null, pats = null;
function index() {
  exact = new Map(); pats = [];
  for (const k in S.en) { if (k.slice(0, 2) !== 'c.') continue; const s = S.en[k];
    if (s.indexOf('{') < 0) { if (!exact.has(s)) exact.set(s, k); continue; }
    const names = []; const re = new RegExp('^' + s.replace(/[.*+?^$()|[\]\\]/g, '\\$&').replace(/\{(\w+)\}/g, (m, n) => { names.push(n); return '(.+?)'; }) + '$');
    pats.push({ re, names, k }); }
}
function tx(s) {
  if (s == null || lang() === 'en') return s;
  if (!exact) index();
  const k = exact.get(s); if (k) return t(k);
  for (const p of pats) { const m = p.re.exec(s); if (m) { const v = {}; p.names.forEach((n, i) => (v[n] = m[i + 1])); return t(p.k, v); } }
  return s;
}
